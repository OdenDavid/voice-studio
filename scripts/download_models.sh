#!/bin/bash
# Local Voice Studio — model download management.
# Downloads (resumable, retrying):
#   1. Pocket TTS x86_64 macOS binary (MIT)
#   2. MOSS-TTS-Nano ONNX weights (Apache-2.0, ungated)
#   3. Pocket TTS English model weights (CC-BY-4.0)
#         - ungated variant (no voice cloning) by default
#         - full weights if HF_TOKEN is set and the user accepted the terms
#             at https://huggingface.co/kyutai/pocket-tts
set -uo pipefail

cd "$(dirname "$0")/.."

BIN_URL="https://github.com/kyutai-labs/pocket-tts/releases/download/v4.0.1/pocket-tts-3.3.0-x86_64-apple-darwin.tar.gz"
HF_BASE="https://huggingface.co"
MOSS_TTS="OpenMOSS-Team/MOSS-TTS-Nano-100M-ONNX"
MOSS_CODEC="OpenMOSS-Team/MOSS-Audio-Tokenizer-Nano-ONNX"
PTTS_FULL="kyutai/pocket-tts"
PTTS_NO_CLONE="kyutai/pocket-tts-without-voice-cloning"

dl() { # dl <url> <dest>
  mkdir -p "$(dirname "$2")"
  echo "  → $2"
  if [ -n "${HF_TOKEN:-}" ]; then
    curl -sL --retry 100 --retry-delay 10 --retry-all-errors \
      -H "Authorization: Bearer $HF_TOKEN" \
      --speed-time 20 --speed-limit 2000 -C - -o "$2" "$1"
  else
    curl -sL --retry 100 --retry-delay 10 --retry-all-errors \
      --speed-time 20 --speed-limit 2000 -C - -o "$2" "$1"
  fi
  echo "  ✓ $2"
}

# Force a clean download (no resume): required when replacing a different
# variant of the same file, e.g. ungated -> gated Pocket TTS weights.
dl_fresh() { # dl_fresh <url> <dest>
  mkdir -p "$(dirname "$2")"
  echo "  → $2 (fresh download)"
  if [ -n "${HF_TOKEN:-}" ]; then
    curl -sL --retry 100 --retry-delay 10 --retry-all-errors \
      -H "Authorization: Bearer $HF_TOKEN" \
      --speed-time 20 --speed-limit 2000 -o "$2" "$1"
  else
    curl -sL --retry 100 --retry-delay 10 --retry-all-errors \
      --speed-time 20 --speed-limit 2000 -o "$2" "$1"
  fi
  echo "  ✓ $2"
}

echo "== 1/4 Pocket TTS binary =="
mkdir -p tools
if [ ! -x tools/pocket-tts-3.3.0-x86_64-apple-darwin/pocket-tts ]; then
  dl "$BIN_URL" tools/pocket-tts.tar.gz
  tar -xzf tools/pocket-tts.tar.gz -C tools
else
  echo "  (already present)"
fi

echo "== 2/4 MOSS-TTS-Nano ONNX weights =="
mkdir -p models/moss_onnx/MOSS-TTS-Nano-100M-ONNX
for f in browser_poc_manifest.json moss_tts_decode_step.onnx \
         moss_tts_global_shared.data moss_tts_local_cached_step.onnx \
         moss_tts_local_decoder.onnx moss_tts_local_fixed_sampled_frame.onnx \
         moss_tts_local_shared.data moss_tts_prefill.onnx tokenizer.model \
         tts_browser_onnx_meta.json; do
  if [ ! -s "models/moss_onnx/MOSS-TTS-Nano-100M-ONNX/$f" ]; then
    dl "$HF_BASE/$MOSS_TTS/resolve/main/$f" "models/moss_onnx/MOSS-TTS-Nano-100M-ONNX/$f"
  fi
done

mkdir -p models/moss_onnx/MOSS-Audio-Tokenizer-Nano-ONNX
for f in codec_browser_onnx_meta.json moss_audio_tokenizer_decode_full.onnx \
         moss_audio_tokenizer_decode_shared.data moss_audio_tokenizer_decode_step.onnx \
         moss_audio_tokenizer_encode.data moss_audio_tokenizer_encode.onnx; do
  if [ ! -s "models/moss_onnx/MOSS-Audio-Tokenizer-Nano-ONNX/$f" ]; then
    dl "$HF_BASE/$MOSS_CODEC/resolve/main/$f" "models/moss_onnx/MOSS-Audio-Tokenizer-Nano-ONNX/$f"
  fi
done

echo "== 3/4 Pocket TTS weights =="
mkdir -p models/pocket_tts/english
if [ -n "${HF_TOKEN:-}" ]; then
  echo "HF_TOKEN detected — downloading full (voice-cloning) English weights."
  # The ungated file is a different asset: never resume into it.
  if [ -s models/pocket_tts/english/model.safetensors ]; then
    mv models/pocket_tts/english/model.safetensors \
       models/pocket_tts/english/model.safetensors.ungated.bak
  fi
  dl_fresh "$HF_BASE/$PTTS_FULL/resolve/main/languages/english/model.safetensors" \
     models/pocket_tts/english/model.safetensors
  echo "Verify voice cloning is available:"
  echo "  .venv/bin/python -c \"import sys; sys.path.insert(0,'app'); from backend.engines.registry import _ENGINES; print(_ENGINES['pocket'].weights_support_cloning())\""
else
  echo "No HF_TOKEN — downloading ungated weights (no voice cloning, fallback only)."
  echo "For full voice cloning: accept the terms at $HF_BASE/$PTTS_FULL, then"
  echo "  export HF_TOKEN=... and re-run this script."
  if [ ! -s models/pocket_tts/english/model.safetensors ]; then
    dl "$HF_BASE/$PTTS_NO_CLONE/resolve/main/languages/english/model.safetensors" \
       models/pocket_tts/english/model.safetensors
  fi
fi
if [ ! -s models/pocket_tts/english/tokenizer.json ]; then
  dl "$HF_BASE/$PTTS_NO_CLONE/resolve/main/languages/english/tokenizer.json" \
     models/pocket_tts/english/tokenizer.json
fi

echo "== 4/4 Pocket TTS local config =="
cat > models/pocket_tts/english_local.yaml <<'EOF'
# Generated by scripts/download_models.sh — all paths are LOCAL.
weights_path: __MODEL_PATH__
weights_path_without_voice_cloning: __MODEL_PATH__
default_temperature: 0.3

replace_characters:
  '’': "'"
  '‘': "'"

flow_lm:
  insert_bos_before_voice: true
  dtype: float32
  flow:
    depth: 6
    dim: 512
  transformer:
    d_model: 1024
    hidden_scale: 4
    max_period: 10000
    num_heads: 16
    num_layers: 6
  lookup_table:
    dim: 1024
    n_bins: 4000
    tokenizer: tokenizers
    tokenizer_path: __TOKENIZER_PATH__

mimi:
  dtype: float32
  sample_rate: 24000
  inner_dim: 32
  outer_dim: 512
  channels: 1
  frame_rate: 12.5
  seanet:
    dimension: 512
    channels: 1
    n_filters: 64
    n_residual_layers: 1
    ratios:
    - 6
    - 5
    - 4
    kernel_size: 7
    residual_kernel_size: 3
    last_kernel_size: 3
    dilation_base: 2
    pad_mode: constant
    compress: 2
  transformer:
    d_model: 512
    num_heads: 8
    num_layers: 2
    layer_scale: 0.01
    context: 250
    dim_feedforward: 2048
    input_dimension: 512
    output_dimensions:
    - 512
  quantizer:
    dimension: 32
    output_dimension: 512
EOF
MODEL_PATH="$(pwd)/models/pocket_tts/english/model.safetensors"
TOKENIZER_PATH="$(pwd)/models/pocket_tts/english/tokenizer.json"
sed -i '' "s|__MODEL_PATH__|$MODEL_PATH|; s|__TOKENIZER_PATH__|$TOKENIZER_PATH|" \
  models/pocket_tts/english_local.yaml

echo "Done."
